/** 从题目文本判断题型（调用方没传时的兜底） */
export function inferQuestionKind(question = ''): 'tech' | 'soft' {
  const t = String(question);
  if (/自我介绍|离职|offer|跳槽|转行|职业规划|抗压|心态|沟通|协作|冲突|考公|为什么想|个人优势|缺点/.test(t)) {
    return 'soft';
  }
  return 'tech';
}

